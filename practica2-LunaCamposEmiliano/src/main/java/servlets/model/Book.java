package servlets.model;

/**
 *
 * @author emicosmic
 */
public class Book {
    
    String nombre, autor;
    double precio;
    
    public Book(String nombre, String autor,double precio){
        this.nombre=nombre;
        this.autor=autor;
        this.precio=precio;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public String getAutor() {
        return autor;
    }

    public void setAutor(String autor) {
        this.autor = autor;
    }

    public double getPrecio() {
        return precio;
    }

    public void setPrecio(double precio) {
        this.precio = precio;
    }
    
    
}
